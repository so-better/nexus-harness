const dictionaries: Record<AppLanguage, Record<MessageKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS
};

/**
 * 当前界面语言；修改后模板会因读取该 ref 自动重渲染。
 */
export const locale = ref<AppLanguage>('zh-CN');

/**
 * 切换界面语言并同步页面 lang。
 */
export const setLocale = (language: AppLanguage): void => {
  locale.value = language;
  document.documentElement.lang = language;
};

/**
 * 读取当前语言文案；缺失 key 时回退中文。
 */
export const t = (key: MessageKey): string =>
  dictionaries[locale.value][key] ?? dictionaries['zh-CN'][key] ?? key;
